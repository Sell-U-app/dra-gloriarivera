  var openBtn = document.getElementById('menu-open-btn');
  var closeBtn = document.getElementById('menu-close-btn');
  var overlay = document.getElementById('gr-overlay');
  function setMobile(open){
    if(!overlay) return;
    overlay.classList.toggle('open', open);
    overlay.setAttribute('aria-hidden', open ? 'false' : 'true');
    document.body.style.overflow = open ? 'hidden' : '';
  }
  if(openBtn) openBtn.addEventListener('click', function(){ setMobile(true); });
  if(closeBtn) closeBtn.addEventListener('click', function(){ setMobile(false); });
  if(overlay) overlay.querySelectorAll('.gr-overlay-link, .gr-overlay-cta').forEach(function(a){
    a.addEventListener('click', function(){ setMobile(false); });
  });
})();

// TOC active section
(function(){
  var tocLinks = document.querySelectorAll('#tocList a[data-toc]');
  if(!tocLinks.length) return;
  var sections = ['responsable','propiedad-intelectual','responsabilidad','legislacion']
    .map(function(id){ return document.getElementById(id); }).filter(Boolean);
  function recompute(){
    var trigger = window.innerHeight * 0.35;
    var candidate = sections[0] ? sections[0].id : null;
    for(var i=0; i<sections.length; i++){
      var rect = sections[i].getBoundingClientRect();
      if(rect.top - trigger <= 0) candidate = sections[i].id;
      else break;
    }
    tocLinks.forEach(function(a){
      a.classList.toggle('is-active', a.dataset.toc === candidate);
    });
  }
  window.addEventListener('scroll', recompute, { passive:true });
  window.addEventListener('resize', recompute);
  recompute();
})();
