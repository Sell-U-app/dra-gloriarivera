        <article class="art-body" id="article-body">
          <p>
            La primera pregunta que recibo en consulta no es <em>cuánto duele</em> ni <em>cuánto dura</em>. Es cuánto cuesta. Y casi siempre viene seguida de un silencio: la persona ya pidió cotizaciones y no entiende por qué unas dicen seis millones y otras catorce, por el mismo nombre — Invisalign. Este artículo es la respuesta larga que me gustaría darle a cada persona antes de que pague una valoración. Sin maquillaje, sin asteriscos.
          </p>

          <h2 id="rango-real"><span class="h2-num">01 · Sección</span>El rango real, sin maquillaje</h2>
          <p>
            En Bogotá, en 2026, un tratamiento completo con Invisalign® hecho por un ortodoncista certificado se mueve entre <strong> 8 y 15 millones de pesos </strong>. Es un rango amplio a propósito: no es un precio único porque no es un producto único. Es un plan clínico que se diseña sobre tu boca, tus dientes, tu mordida y tus tiempos.
          </p>
          <p>
            Cuando ves rangos más bajos — cinco millones, cuatro y medio — generalmente está pasando una de tres cosas: o el sistema no es Invisalign sino un alineador genérico de marca local, o el tratamiento está incompleto (faltan controles, refinamientos o retenedores), o quien atiende no es ortodoncista. Las tres cosas pueden costarte más caro después que pagar bien la primera vez.
          </p>
          <p>
            El rango alto, por encima de quince millones, suele incluir casos quirúrgicos, casos combinados con cirugía ortognática o tratamientos en estudios de muy alta gama donde el precio refleja el tiempo dedicado y la infraestructura. No es necesariamente mejor: es distinto.
          </p>

          <div class="feat-block">
            <span class="feat-eyebrow">Punto clave</span>
            <p>El precio de Invisalign no se cotiza por número de alineadores. Se cotiza por la complejidad del caso, los objetivos del plan y el tiempo clínico que toma sostenerlo bien. Desconfía de cualquier propuesta que te dé un número antes de mirarte la boca.</p>
          </div>

          <h2 id="que-incluye"><span class="h2-num">02 · Sección</span>Qué incluye un plan completo</h2>
          <p>
            Cuando yo cotizo un caso, el número que recibes incluye todo lo que vas a necesitar desde el día uno hasta el último retenedor. No hay extras escondidos. Estos son los componentes que un plan honesto debería tener:
          </p>
          <ul class="list-check">
            <li><strong>Valoración clínica completa.</strong> No la de cinco minutos para vender un tratamiento. La de cuarenta minutos donde se evalúan dientes, encías, articulación, hueso y se decide si Invisalign tiene sentido para ti.</li>
            <li><strong>Escaneo intraoral 3D con iTero®.</strong> Sin moldes de silicona, sin radiografías innecesarias. El escaneo se procesa el mismo día y permite ver una simulación inicial del resultado.</li>
            <li><strong>Planificación digital personalizada por el ortodoncista.</strong> No por un técnico en otro país. Cada movimiento dental se diseña, se revisa y se aprueba por quien va a acompañar el caso.</li>
            <li><strong>Todos los alineadores que necesite el caso.</strong> Doce, treinta, cincuenta — el número lo dicta la biomecánica, no el contrato.</li>
            <li><strong>Controles periódicos durante todo el tratamiento.</strong> Habitualmente cada 6–8 semanas, siempre con la misma ortodoncista — no con un asistente distinto cada vez.</li>
            <li><strong>Refinamientos incluidos.</strong> Si al final del set inicial hay detalles que ajustar, se ordenan alineadores adicionales sin costo extra. Es parte del trabajo, no un upgrade.</li>
            <li><strong>Retenedores fijos y removibles al finalizar.</strong> Porque sin retención, el tratamiento no se sostiene. Cualquier plan que los venda aparte está incompleto.</li>
          </ul>
          <p>
            Si en una cotización falta cualquiera de estos siete elementos, no estás comparando lo mismo. Y la diferencia de precio que parece atractiva al inicio se paga después — en refinamientos cobrados aparte, en retenedores que cuestan un millón más, o peor, en una recidiva que te lleva a empezar otra vez.
          </p>

          <h2 id="por-que-distinto"><span class="h2-num">03 · Sección</span>Por qué tu caso puede costar distinto al de un amigo</h2>
          <p>
            Es una conversación habitual: <em>"a mi prima le cotizaron nueve y a mí trece, por el mismo Invisalign"</em>. Casi siempre hay una explicación que tiene sentido. Estos son los factores que mueven el precio dentro del rango:
          </p>
          <h3>1. La complejidad biomecánica del caso</h3>
          <p>Un apiñamiento leve con mordida estable necesita pocos alineadores y movimientos predecibles. Una mordida abierta, una sobremordida profunda o una asimetría esquelética necesitan más planificación, más alineadores, más controles y a veces auxiliares como elásticos o attachments adicionales. No es lo mismo, aunque ambos se llamen Invisalign.</p>
          <h3>2. El producto Invisalign específico</h3>
          <p>Invisalign tiene varias modalidades — Express, Lite, Moderate, Comprehensive, First — y cada una está pensada para un tipo de caso y de objetivo. La diferencia de costo del producto en sí mismo, que paga el consultorio a Align Technology, ya se mueve en varios millones entre las modalidades.</p>
          <h3>3. El tiempo clínico que toma el plan</h3>
          <p>Un tratamiento de 8 meses y uno de 22 meses no cuestan lo mismo de operar, aunque usen alineadores parecidos. El precio refleja, entre otras cosas, el número de citas, la duración del acompañamiento y la responsabilidad clínica sostenida en el tiempo.</p>
          <blockquote>
            <p>Un buen plan no se diseña en una tarde. Se diseña a lo largo de varios días, con los archivos abiertos, mirando una y otra vez los movimientos hasta que el resultado tiene sentido en ti — no en un caso parecido al tuyo.</p>
            <cite>Dra. Gloria Rivera</cite>
          </blockquote>
          <h3>4. Quién planifica y acompaña</h3>
          <p>Hay consultorios donde el plan lo diseña un técnico, el tratamiento lo lleva un asistente y el ortodoncista firma. Hay otros — el mío entre ellos — donde una sola persona ve cada caso de principio a fin. La diferencia se siente en la calidad del resultado y, sí, también en el precio.</p>

