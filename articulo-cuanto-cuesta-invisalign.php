          <h2 id="precio-filtro"><span class="h2-num">06 · Sección</span>El precio como filtro, no como barrera</h2>
          <p>Voy a decir algo que probablemente cuesta clientes y aun así prefiero dejarlo escrito: si el precio es lo único que te importa, esta no es la práctica para ti, y está bien. Hay opciones más económicas en la ciudad, algunas razonables, otras no tanto. La elección es tuya.</p>
          <p>Lo que sí puedo prometer — porque depende de mí — es que cuando entras a este consultorio, cada peso que pagas está pagado por trabajo clínico hecho por la misma persona que firma tu historia. No hay intermediarios, no hay residentes practicando, no hay decisiones que se toman en otro país. Es ortodoncia hecha despacio, con la responsabilidad de mirar cada movimiento como si fuera el único caso del día.</p>
