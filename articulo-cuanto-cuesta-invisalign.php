          <h2 id="no-deberia-pagar"><span class="h2-num">04 · Sección</span>Lo que no deberías estar pagando</h2>
          <p>Igual de importante que entender qué incluye un plan honesto, es saber qué no debería aparecer como cobro adicional cuando ya firmaste un tratamiento completo:</p>
          <ul class="list-x">
            <li>Refinamientos al final del tratamiento como si fueran un servicio aparte.</li>
            <li>Retenedores al terminar — fijos o removibles — cobrados por separado.</li>
            <li>Cada control mensual facturado como consulta independiente.</li>
            <li>Citas de emergencia razonables por un attachment desprendido o un alineador roto.</li>
            <li>Acceso a las imágenes y archivos de tu propio caso.</li>
            <li>Cambios menores al plan inicial cuando el caso lo requiere clínicamente.</li>
          </ul>
          <p>No estoy diciendo que cualquier consultorio que cobre alguno de estos ítems esté actuando de mala fe. Pero sí digo que cuando comparas cotizaciones, conviene preguntar abiertamente: <em>¿esto está incluido o se paga aparte?</em> La respuesta te dice más sobre la práctica que el precio en sí mismo.</p>

          <h2 id="como-se-paga"><span class="h2-num">05 · Sección</span>Cómo se paga: opciones reales</h2>
          <p>Un tratamiento adulto no es una compra impulsiva. La gran mayoría de pacientes lo paga en cuotas a lo largo del primer año, con un abono inicial al firmar el plan y mensualidades que se distribuyen mientras avanza el tratamiento. Estas son las opciones que solemos ofrecer:</p>
