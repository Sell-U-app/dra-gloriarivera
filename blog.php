function getFilteredArticles(showFeatured){
  return ARTICLES
    .filter(function(a){ return !(showFeatured && a.featured); })
    .filter(function(a){ return state.category === 'Todos' || a.category === state.category; })
    .filter(function(a){
      if(!state.debouncedQuery) return true;
      var q = state.debouncedQuery;
      return a.title.toLowerCase().indexOf(q) >= 0
          || a.excerpt.toLowerCase().indexOf(q) >= 0
          || a.category.toLowerCase().indexOf(q) >= 0;
    })
    .sort(function(a,b){ return new Date(b.date) - new Date(a.date); });
}

function getCounts(){
  var filtered = ARTICLES.filter(function(a){
    if(!state.debouncedQuery) return true;
    var q = state.debouncedQuery;
    return a.title.toLowerCase().indexOf(q) >= 0
        || a.excerpt.toLowerCase().indexOf(q) >= 0
        || a.category.toLowerCase().indexOf(q) >= 0;
  });
  var c = { Todos: filtered.length };
  CATEGORIES.slice(1).forEach(function(cat){
    c[cat] = filtered.filter(function(a){ return a.category === cat; }).length;
  });
  return c;
}

function renderChips(){
  var counts = getCounts();
  var html = CATEGORIES.map(function(cat){
    var active = state.category === cat;
    var count = counts[cat] || 0;
    var disabled = count === 0 && cat !== 'Todos';
    return '<button class="blog-chip" data-cat="' + cat + '" aria-pressed="' + active + '"' + (disabled ? ' disabled style="opacity:.45;cursor:not-allowed"' : '') + '>'
      + '<span>' + cat + '</span><span class="count">' + count + '</span></button>';
  }).join('');
  document.getElementById('blog-chips').innerHTML = html;
}

function renderPagination(currentPage, totalPages){
  var html = '<nav class="blog-pagination" aria-label="Paginación del blog">';
  html += '<button class="page-btn" data-page="' + (currentPage-1) + '"' + (currentPage === 1 ? ' disabled' : '') + ' aria-label="Página anterior"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="m15 18-6-6 6-6"/></svg></button>';
  for(var n=1; n<=totalPages; n++){
    var isCurrent = n === currentPage;
    html += '<button class="page-btn" data-page="' + n + '"' + (isCurrent ? ' aria-current="page"' : '') + ' aria-label="Página ' + n + '">' + n + '</button>';
  }
  html += '<button class="page-btn" data-page="' + (currentPage+1) + '"' + (currentPage === totalPages ? ' disabled' : '') + ' aria-label="Página siguiente"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="m9 18 6-6-6-6"/></svg></button>';
  html += '<span class="page-info">Página ' + currentPage + ' de ' + totalPages + '</span>';
  html += '</nav>';
  return html;
}

function render(){
  // Featured (only when no filter/search)
  var showFeatured = state.category === 'Todos' && !state.debouncedQuery;
  var featuredEl = document.getElementById('featured-section');
  if(showFeatured){
    var feat = ARTICLES.find(function(a){ return a.featured; });
    featuredEl.innerHTML = renderFeatured(feat);
    featuredEl.style.display = '';
  } else {
    featuredEl.innerHTML = '';
    featuredEl.style.display = 'none';
  }

  // Heading
  var heading = 'Últimos artículos';
  if(state.debouncedQuery) heading = 'Resultados de búsqueda';
  else if(state.category !== 'Todos') heading = 'Artículos sobre ' + state.category.toLowerCase();
  document.getElementById('grid-heading').textContent = heading;

  // Grid
  var filtered = getFilteredArticles(showFeatured);
  var total = filtered.length;
  document.getElementById('article-count').textContent = total;
  document.getElementById('article-word').textContent = total === 1 ? 'artículo' : 'artículos';

  var totalPages = Math.max(1, Math.ceil(total / ARTICLES_PER_PAGE));
  var safePage = Math.min(state.page, totalPages);
  var start = (safePage - 1) * ARTICLES_PER_PAGE;
  var pageItems = filtered.slice(start, start + ARTICLES_PER_PAGE);
  var wrap = document.getElementById('grid-wrap');

  if(total === 0){
    wrap.innerHTML = '<div class="blog-empty" role="status"><div class="glyph">"</div>'
      + '<h3>No encontramos artículos sobre eso aún.</h3>'
      + '<p>Pregúntale a la doctora directamente — responde personalmente las consultas que llegan por WhatsApp.</p>'
      + '</div>';
  } else {
    var cards = pageItems.map(renderArticleCard).join('');
    wrap.innerHTML = '<div class="article-grid grid-fade" key="' + state.category + '-' + state.debouncedQuery + '-' + safePage + '">' + cards + '</div>'
      + renderPagination(safePage, totalPages);
  }

  renderChips();
}

