function renderGrid(animate){
  var grid1 = document.getElementById('case-grid-1');
  var grid2 = document.getElementById('case-grid-2');
  var inter = document.getElementById('intermediate-cta');
  var empty = document.getElementById('case-empty');

  var filtered = activeType === 'todos' ? CASES : CASES.filter(function(c){ return c.type === activeType; });

  function paint(){
    if(filtered.length === 0){
      grid1.innerHTML = ''; grid2.innerHTML = '';
      inter.style.display = 'none';
      empty.style.display = 'block';
      return;
    }
    empty.style.display = 'none';

    var first = filtered.slice(0, 3);
    var rest  = filtered.slice(3);

    grid1.innerHTML = first.map(caseCardHTML).join('');
    grid2.innerHTML = rest.map(caseCardHTML).join('');
    inter.style.display = rest.length > 0 ? 'grid' : 'none';

    document.querySelectorAll('.case-card').forEach(function(card){
      card.addEventListener('click', function(){
        var id = card.getAttribute('data-id');
        var data = CASES.find(function(c){ return c.id === id; });
        if(data){ lastTrigger = card; openModal(data); }
      });
      card.addEventListener('keydown', function(e){
        if(e.key === 'Enter' || e.key === ' '){
          e.preventDefault();
          var id = card.getAttribute('data-id');
          var data = CASES.find(function(c){ return c.id === id; });
          if(data){ lastTrigger = card; openModal(data); }
        }
      });
    });
    grid1.classList.remove('fading');
    grid2.classList.remove('fading');
  }

  if(animate){
    grid1.classList.add('fading');
    grid2.classList.add('fading');
    setTimeout(paint, 200);
  } else {
    paint();
  }
}

