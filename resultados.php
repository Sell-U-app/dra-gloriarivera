function renderPills(){
  var wrap = document.getElementById('filter-pills');
  wrap.innerHTML = '';
  TYPES.forEach(function(t){
    var btn = document.createElement('button');
    btn.type = 'button';
    btn.setAttribute('role', 'tab');
    btn.textContent = t.label;
    btn.setAttribute('aria-pressed', activeType === t.id);
    btn.setAttribute('aria-selected', activeType === t.id);
    if(activeType === t.id) btn.classList.add('active');
    btn.addEventListener('click', function(){
      if(activeType === t.id) return;
      activeType = t.id;
      renderPills();
      renderGrid(true);
    });
    wrap.appendChild(btn);
  });
}

