function openModal(data){
  modalContent.innerHTML = modalBodyHTML(data);
  var sw = window.innerWidth - document.documentElement.clientWidth;
  document.documentElement.style.setProperty('--scrollbar-width', sw + 'px');
  document.body.classList.add('modal-open');
  backdrop.classList.add('open');
  backdrop.setAttribute('aria-hidden', 'false');
  setTimeout(function(){ modalCloseBtn.focus(); }, 80);
}

function closeModal(){
  backdrop.classList.add('closing');
  setTimeout(function(){
    backdrop.classList.remove('open');
    backdrop.classList.remove('closing');
    backdrop.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    modalContent.innerHTML = '';
    if(lastTrigger && lastTrigger.focus) lastTrigger.focus();
  }, 200);
}

modalCloseBtn.addEventListener('click', closeModal);
backdrop.addEventListener('click', function(e){ if(e.target === backdrop) closeModal(); });
document.addEventListener('keydown', function(e){
  if(e.key === 'Escape' && backdrop.classList.contains('open')) closeModal();
  if(e.key === 'Tab' && backdrop.classList.contains('open')){
    var focusable = backdrop.querySelectorAll('button, [href], [tabindex]:not([tabindex="-1"])');
    if(!focusable.length) return;
    var first = focusable[0], last = focusable[focusable.length-1];
    if(e.shiftKey && document.activeElement === first){ e.preventDefault(); last.focus(); }
    else if(!e.shiftKey && document.activeElement === last){ e.preventDefault(); first.focus(); }
  }
});

