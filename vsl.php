      window.scrollTo({ top: top, behavior: 'smooth' });
    }
  });
});

// Tracking helper
function trackEvent(name, params){
  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push(Object.assign({ event: name }, params || {}));
}
trackEvent('vsl_page_view', { page: '/conoce-tu-plan' });

// LeadConnector calendar: failsafe para ocultar skeleton + tracking de visibilidad + postMessage
(function(){
  var embed = document.getElementById('cal-embed');
  var skel  = document.getElementById('cal-skel');
  if(!embed) return;

  // El onload del iframe oculta el skeleton; este intervalo es defensivo (8 s).
  var tries = 0;
  var t = setInterval(function(){
    tries++;
    if(tries > 32 && skel){ skel.style.display = 'none'; clearInterval(t); }
  }, 250);

  // vsl_calendar_view al entrar al viewport
  if('IntersectionObserver' in window){
    var seen = false;
    var io = new IntersectionObserver(function(entries){
      entries.forEach(function(e){
        if(e.isIntersecting && !seen){
          seen = true;
          trackEvent('vsl_calendar_view');
        }
      });
    }, { threshold: 0.3 });
    io.observe(embed);
  }

  // Eventos postMessage del widget (LeadConnector / msgsndr) → dataLayer
  window.addEventListener('message', function(e){
    if(!e.data) return;
    var d = e.data;
    var ev = (typeof d === 'object' && d.event) ? String(d.event)
           : (typeof d === 'string' ? d : '');
    if(!ev) return;
    if(/booking|appointment|calendar|leadconnector|msgsndr/i.test(ev)){
      trackEvent('vsl_calendar_' + ev.toLowerCase().replace(/[^a-z0-9_]+/g,'_'));
    }
  });
})();

// Vidalytics: tracking del primer play
(function(){
  var seen = false;
  window.addEventListener('message', function(e){
    if(!e.data) return;
    var d = e.data;
    var src = (typeof d === 'object' && d.source) ? String(d.source) : '';
    var ev  = (typeof d === 'object' && d.event)  ? String(d.event)  : (typeof d === 'string' ? d : '');
    if(/vidalytics/i.test(src) || /vidalytics/i.test(ev)){
      if(!seen && /play|start/i.test(ev)){
        seen = true;
        trackEvent('vsl_video_play');
      }
    }
  });
})();
