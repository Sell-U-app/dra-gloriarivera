(function(){
  var nav = document.getElementById('gr-nav');
  var util = document.getElementById('gr-utility');
  function onScroll(){
    var y = window.scrollY;
    if(y > 40){ nav.classList.add('scrolled'); util.classList.add('hidden'); }
    else { nav.classList.remove('scrolled'); util.classList.remove('hidden'); }
  }
  window.addEventListener('scroll', onScroll, { passive:true });
  onScroll();

  var openBtn = document.getElementById('menu-open-btn');
  var closeBtn = document.getElementById('menu-close-btn');
  var overlay = document.getElementById('gr-overlay');
  function setMobile(open){
    if(!overlay) return;
    overlay.classList.toggle('open', open);
    overlay.setAttribute('aria-hidden', open ? 'false' : 'true');
    document.body.style.overflow = open ? 'hidden' : '';
  }
  if(openBtn) openBtn.addEventListener('click', function(){ setMobile(true); });
  if(closeBtn) closeBtn.addEventListener('click', function(){ setMobile(false); });
  if(overlay) overlay.querySelectorAll('.gr-overlay-link, .gr-overlay-cta').forEach(function(a){
    a.addEventListener('click', function(){ setMobile(false); });
  });
})();

document.querySelectorAll('[data-scroll]').forEach(function(btn){
  btn.addEventListener('click', function(e){
    var sel = btn.getAttribute('data-scroll');
    var el = document.querySelector(sel);
    if(el){
      e.preventDefault();
      var top = el.getBoundingClientRect().top + window.scrollY - 80;
      window.scrollTo({ top: top, behavior: 'smooth' });
    }
  });
});

(function(){
  var embed = document.getElementById('cal-embed');
  var skel  = document.getElementById('cal-skel');
  if(!embed || !skel) return;
  var iframe = embed.querySelector('iframe');
  function hide(){ skel.style.display = 'none'; }
  if(iframe){
    if(iframe.complete || iframe.readyState === 'complete'){ hide(); }
    iframe.addEventListener('load', hide);
    setTimeout(hide, 4000);
  }
  window.addEventListener('message', function(e){
    if(!e.data || typeof e.data !== 'object') return;
    var ev = e.data.event || e.data.type;
    if(typeof ev !== 'string') return;
    if(/(booking|appointment|leadconnector)/i.test(ev)){
      window.dataLayer = window.dataLayer || [];
      window.dataLayer.push({ event: 'cal_' + ev });
    }
  });
})();
