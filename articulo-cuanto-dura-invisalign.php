    <div class="bt-prose">
      <ol class="bt-factors">
        <li class="bt-factor">
          <span class="num" aria-hidden="true">01</span>
          <div>
            <h3>Complejidad del caso</h3>
            <p>
              Es el factor que más define la duración total. Un apiñamiento leve no toma el mismo
              tiempo que una mordida cruzada con apiñamiento severo. Movimientos complejos como
              rotaciones, extrusiones o cambios verticales requieren más alineadores y más tiempo
              biológico de adaptación. Esto se define en tu diagnóstico inicial, no en tu preferencia.
            </p>
          </div>
        </li>

        <li class="bt-factor">
          <span class="num" aria-hidden="true">02</span>
          <div>
            <h3>Horas reales de uso diario</h3>
            <p>
              Aquí es donde la mayoría de los tratamientos se alargan. Invisalign® requiere
              22 horas al día de uso. Si llegas a 22 horas, el tratamiento avanza como se planificó
              en ClinCheck. Si llegas solo a 18 o 19 horas, los movimientos planificados no se logran
              completamente y los alineadores siguientes ya no encajan bien. Esto requiere rehacer
              alineadores o alargar el tratamiento.
            </p>
          </div>
        </li>

        <li class="bt-factor">
          <span class="num" aria-hidden="true">03</span>
          <div>
            <h3>Disciplina al cambiar alineadores</h3>
            <p>
              Los alineadores se cambian según indicación profesional, generalmente cada 7 a 14 días.
              Cambiarlos antes o después de lo indicado afecta el avance: si los cambias antes, los
              dientes no tienen tiempo suficiente para llegar a la posición planificada; si los cambias
              después, retrasas todo el cronograma. La disciplina aquí es tan importante como las
              22 horas al día.
            </p>
          </div>
        </li>

        <li class="bt-factor">
          <span class="num" aria-hidden="true">04</span>
          <div>
            <h3>Asistencia a controles</h3>
            <p>
              Los controles cada 6 a 8 semanas son donde verifico que los dientes están donde deberían
              estar según el plan ClinCheck. Si no asistes y un movimiento no está sucediendo como se
              planificó, no podemos detectarlo a tiempo y corregirlo. Pacientes que faltan a controles
              tienden a necesitar más refinamientos al final del tratamiento.
            </p>
          </div>
        </li>

        <li class="bt-factor">
          <span class="num" aria-hidden="true">05</span>
          <div>
            <h3>Respuesta biológica individual</h3>
            <p>
              Cada paciente tiene una respuesta biológica única al movimiento dental. Algunos huesos
              responden más rápido a las fuerzas aplicadas, otros más lentamente. Esto no es algo que
              puedas controlar, pero sí algo que puedo anticipar parcialmente en valoración según tu
              edad, salud periodontal y tipo de hueso. Por eso los tiempos siempre se dan en rangos,
              nunca como cifras exactas.
            </p>
          </div>
        </li>
      </ol>
