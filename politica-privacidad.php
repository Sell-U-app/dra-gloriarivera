(function(){
  var tocLinks = document.querySelectorAll('[data-toc-link]');
  if(!tocLinks.length) return;
  var sections = ['responsable','datos-y-finalidades','derechos','seguridad-terceros']
    .map(function(id){ return document.getElementById(id); }).filter(Boolean);
  function setActive(id){
    tocLinks.forEach(function(a){
      a.classList.toggle('active', a.getAttribute('href') === '#'+id);
    });
  }
  function recompute(){
    var trigger = window.innerHeight * 0.35;
    var candidate = sections[0] ? sections[0].id : null;
    for(var i=0; i<sections.length; i++){
      var rect = sections[i].getBoundingClientRect();
      if(rect.top - trigger <= 0) candidate = sections[i].id;
      else break;
    }
    setActive(candidate);
  }
  window.addEventListener('scroll', recompute, { passive:true });
  window.addEventListener('resize', recompute);
  recompute();
})();
