        <h2>Problemas que Invisalign® <em>suele</em> resolver.</h2>
        <p>Invisalign® ha evolucionado mucho desde sus primeras versiones. Hoy puede tratar la mayoría de los casos que antes solo se hacían con brackets, siempre que la complejidad permita el movimiento controlado con alineadores. Estos son los 8 problemas más frecuentes que trato en mi consulta:</p>
      </div>

      <div class="bp-problems">
        <article class="bp-problem">
          <span class="num">Problema 01</span>
          <h3>Apiñamiento dental</h3>
          <p>Dientes amontonados, torcidos o que se montan unos sobre otros. Invisalign® trata bien apiñamiento leve, moderado y muchos casos avanzados según diagnóstico.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 02</span>
          <h3>Espacios y diastemas</h3>
          <p>Separaciones entre los dientes, especialmente en los anteriores. Los alineadores cierran los espacios de forma controlada y predecible.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 03</span>
          <h3>Sobremordida</h3>
          <p>Los dientes superiores cubren demasiado a los inferiores al cerrar la boca. Tratable con Invisalign® en muchos casos leves y moderados.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 04</span>
          <h3>Mordida abierta</h3>
          <p>Los dientes anteriores no se tocan al cerrar la boca. Puede tratarse con Invisalign® según el origen del problema (dental vs esquelético).</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 05</span>
          <h3>Mordida cruzada</h3>
          <p>Algunos dientes superiores muerden por dentro de los inferiores. Tratable con alineadores en casos dentales moderados.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 06</span>
          <h3>Mordida profunda</h3>
          <p>Los dientes inferiores se ocultan casi completamente al cerrar la boca. Invisalign® puede corregir muchos casos según diagnóstico.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 07</span>
          <h3>Dientes rotados o inclinados</h3>
          <p>Dientes que están girados sobre su eje o inclinados hacia adelante o atrás. Los attachments permiten estos movimientos con precisión.</p>
        </article>
        <article class="bp-problem">
          <span class="num">Problema 08</span>
          <h3>Retratamientos post-ortodoncia</h3>
          <p>Pacientes que ya tuvieron brackets y notan que los dientes se movieron de nuevo (recidiva). Invisalign Express® o Lite® suele ser ideal.</p>
        </article>
